"""Turn Figma variables exports (W3C design-tokens JSON, one file per mode) into a compact TS module.

Usage: python3 scripts/build-tokens.py <CollectionName> <out.ts> <Mode>=<export.json> [<Mode>=<export.json> ...]
Keeps only what the Figma Variables replica shows: group path, name, type and, per mode, the value, the alias
target and the opacity. Groups and variables keep the export order; single-mode number groups are sorted by value,
like Figma lists them.
"""
import json
import sys

collection, out, *mode_args = sys.argv[1:]
modes = [arg.split("=", 1)[0] for arg in mode_args]
exports = [json.load(open(arg.split("=", 1)[1])) for arg in mode_args]


def walk(node, path, acc):
    for key, value in node.items():
        if key.startswith("$") or not isinstance(value, dict):
            continue
        if "$type" in value:
            acc.append((path, key, value))
        else:
            walk(value, path + [key], acc)


def resolve(data, ref):
    """Follow a local reference like "{Alpha.5}" to the token it points to in the same export."""
    node = data
    for part in ref.strip("{}").split("."):
        node = node[part]
    return node


def cell(token, data):
    value = token["$value"]
    ext = token.get("$extensions", {})
    result = {}
    # Alias to a variable of the same collection, exported as a reference string instead of a value
    if isinstance(value, str) and value.startswith("{") and token["$type"] != "string":
        target = resolve(data, value)
        resolved = cell(target, data)
        resolved["alias"] = value.strip("{}").replace(".", "/")
        return resolved
    if token["$type"] == "color":
        result["value"] = value["hex"].upper()
        if value.get("alpha", 1) < 1:
            result["alpha"] = round(value["alpha"] * 100)
    else:
        result["value"] = round(value, 2) if isinstance(value, float) else value
    alias = ext.get("com.figma.aliasData", {}).get("targetVariableName")
    if alias:
        result["alias"] = alias
    # Colour built from an alias + its own opacity (Figma's "colors/primary-dark · 5%")
    composed = ext.get("com.figma.composedColor")
    if composed and composed.get("colorArg", {}).get("type") == "alias":
        result["alias"] = composed["colorArg"]["alias"]["targetVariableName"]
        result["alpha"] = round(composed["opacityArg"]["value"])
        result["ownAlpha"] = True
    return result


per_mode = []
for data in exports:
    acc = []
    walk(data, [], acc)
    per_mode.append(acc)

groups, index = [], {}
for i, (path, name, token) in enumerate(per_mode[0]):
    key = "/".join(path)
    if key not in index:
        index[key] = {"path": path, "tokens": []}
        groups.append(index[key])
    values = []
    for acc, data in zip(per_mode, exports):
        match = next(t for p, n, t in acc if p == path and n == name)
        values.append(cell(match, data))
    index[key]["tokens"].append({"name": name, "type": token["$type"], "values": values})

if len(modes) == 1:
    for g in groups:
        if all(t["type"] == "number" for t in g["tokens"]):
            g["tokens"].sort(key=lambda t: t["values"][0]["value"])

const = collection[0].lower() + collection[1:]
body = json.dumps({"name": collection, "modes": modes, "groups": groups}, ensure_ascii=False, separators=(",", ":"))
with open(out, "w") as f:
    f.write("// Generated by scripts/build-tokens.py from the Figma export. Do not edit by hand.\n")
    f.write('import type { TokenCollection } from "./types";\n\n')
    f.write(f"export const {const}Collection: TokenCollection = {body};\n")
print(collection, modes, sum(len(g["tokens"]) for g in groups), "tokens in", len(groups), "groups")
